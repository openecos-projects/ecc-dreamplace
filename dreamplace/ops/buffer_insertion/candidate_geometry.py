"""Live geometry and identity handling for virtual candidate buffering.

Candidate rows are regenerated by the live Steiner topology.  A candidate's
stable identity is its net/edge/normalized-position key; the absolute DBU
coordinate and RC payload are generation-local caches.
"""

import hashlib
import json
import math
from dataclasses import dataclass

import torch
from torch import nn

_POSITION_DIGITS = 12


def _as_float(value, *, name):
    result = float(value)
    if not math.isfinite(result):
        raise ValueError(f"{name} must be finite")
    return result


def _node_coordinate(live_topology, node_id, *, dbu=False):
    """Resolve one node coordinate from a live topology payload."""

    if node_id is None:
        return None
    node_id = int(node_id)
    if node_id < 0:
        return None
    suffix = "_dbu" if dbu else ""
    x_values = live_topology.get(f"node_x{suffix}")
    y_values = live_topology.get(f"node_y{suffix}")
    if x_values is not None and y_values is not None:
        try:
            if torch.is_tensor(x_values):
                if node_id >= int(x_values.numel()) or node_id >= int(y_values.numel()):
                    return None
                return (
                    float(x_values.reshape(-1)[node_id].detach().cpu().item()),
                    float(y_values.reshape(-1)[node_id].detach().cpu().item()),
                )
            if node_id >= len(x_values) or node_id >= len(y_values):
                return None
            return float(x_values[node_id]), float(y_values[node_id])
        except (IndexError, TypeError, ValueError):
            return None

    coordinates = live_topology.get("coordinates_dbu" if dbu else "coordinates")
    if isinstance(coordinates, dict):
        value = coordinates.get(node_id, coordinates.get(str(node_id)))
        if value is not None and len(value) >= 2:
            return _as_float(value[0], name="x"), _as_float(value[1], name="y")
    return None


def _polyline_coordinate(polyline, normalized_position):
    points = [tuple(map(float, point[:2])) for point in (polyline or ())]
    if len(points) < 2:
        return None
    lengths = []
    total = 0.0
    for start, end in zip(points, points[1:], strict=False):
        length = math.hypot(end[0] - start[0], end[1] - start[1])
        lengths.append(length)
        total += length
    if total <= 0.0:
        return points[0]
    target = max(0.0, min(1.0, normalized_position)) * total
    consumed = 0.0
    for index, length in enumerate(lengths):
        if target <= consumed + length or index == len(lengths) - 1:
            local = 0.0 if length <= 0.0 else (target - consumed) / length
            start, end = points[index], points[index + 1]
            return (
                start[0] + local * (end[0] - start[0]),
                start[1] + local * (end[1] - start[1]),
            )
        consumed += length
    return points[-1]


def _segment_fields(record):
    parent = record.get("parent_node_id")
    children = list(record.get("child_node_ids", ()) or ())
    ratio = record.get("segment_split_ratio")
    if parent is None or len(children) != 1 or ratio is None:
        return None
    ratio = _as_float(ratio, name="segment_split_ratio")
    if not 0.0 < ratio < 1.0:
        raise ValueError("segment_split_ratio must lie in (0, 1)")
    return int(record.get("net_id", -1)), int(parent), int(children[0]), ratio


def candidate_key(record):
    """Return a stable identity independent of candidate row ordering."""

    segment = _segment_fields(record)
    if segment is not None:
        net_id, parent, child, ratio = segment
        return (
            "segment",
            net_id,
            parent,
            child,
            round(ratio, _POSITION_DIGITS),
        )
    tree_node_id = record.get("tree_node_id")
    if tree_node_id is None:
        tree_node_id = record.get("candidate_node_id")
    if tree_node_id is not None and int(tree_node_id) >= 0:
        return ("tree_node", int(record.get("net_id", -1)), int(tree_node_id))
    return (
        "candidate",
        int(record.get("net_id", -1)),
        int(record.get("candidate_id", -1)),
    )


def typed_action_key(record, drive_type):
    return candidate_key(record) + ("drive_type", int(drive_type))


def _candidate_coordinate(record, live_topology):
    segment = _segment_fields(record)
    if segment is not None:
        net_id, parent, child, ratio = segment
        polyline_map = live_topology.get("edge_polylines", {}) or {}
        polyline = polyline_map.get((net_id, parent, child))
        if polyline is None:
            polyline = polyline_map.get((parent, child))
        if polyline is not None:
            coordinate = _polyline_coordinate(polyline, ratio)
            if coordinate is not None:
                return coordinate
        parent_coordinate = _node_coordinate(live_topology, parent, dbu=True)
        child_coordinate = _node_coordinate(live_topology, child, dbu=True)
        if parent_coordinate is None or child_coordinate is None:
            return None
        return (
            (1.0 - ratio) * parent_coordinate[0] + ratio * child_coordinate[0],
            (1.0 - ratio) * parent_coordinate[1] + ratio * child_coordinate[1],
        )
    tree_node_id = record.get("tree_node_id")
    if tree_node_id is None:
        tree_node_id = record.get("candidate_node_id")
    return _node_coordinate(live_topology, tree_node_id, dbu=True)


def _digest_records(records):
    payload = []
    for record in records:
        payload.append(
            {
                "key": candidate_key(record),
                "x_dbu": record.get("x_dbu"),
                "y_dbu": record.get("y_dbu"),
                "segment_length_dbu": record.get("segment_length_dbu"),
                "upstream_length_dbu": record.get("upstream_length_dbu"),
                "downstream_length_dbu": record.get("downstream_length_dbu"),
            }
        )
    serialized = json.dumps(payload, sort_keys=True, separators=(",", ":"))
    return "sha256:" + hashlib.sha256(serialized.encode("utf-8")).hexdigest()


@dataclass(frozen=True)
class CandidateRefreshResult:
    candidate_records: tuple
    candidate_generation: int
    geometry_generation: int
    remapped_activation: object = None
    invalidated_candidate_keys: tuple = ()
    geometry_digest: str = ""
    topology_digest: str = ""

    def to_summary(self):
        return {
            "candidate_generation": int(self.candidate_generation),
            "geometry_generation": int(self.geometry_generation),
            "candidate_count": len(self.candidate_records),
            "invalidated_candidate_count": len(self.invalidated_candidate_keys),
            "invalidated_candidate_keys": list(self.invalidated_candidate_keys),
            "geometry_digest": self.geometry_digest,
            "topology_digest": self.topology_digest,
        }


def refresh_candidate_geometry(
    candidate_state,
    live_topology,
    node_x=None,
    node_y=None,
    node_x_dbu=None,
    node_y_dbu=None,
    runtime_cell_state=None,
    *,
    candidate_generation=None,
    geometry_generation=None,
):
    """Regenerate candidate coordinates and geometry-local fields.

    ``candidate_state`` may be a state object or a sequence of candidate records.
    The state tensors are never mutated here; callers can use
    :func:`remap_candidate_state` after rebuilding a state from the live payload.
    """

    topology = dict(live_topology or {})
    for name, value in (
        ("node_x", node_x),
        ("node_y", node_y),
        ("node_x_dbu", node_x_dbu),
        ("node_y_dbu", node_y_dbu),
    ):
        if value is not None:
            topology[name] = value
    # Geometry records are detached metadata. Copy each coordinate array once
    # instead of synchronizing and extracting a tensor scalar for every edge.
    for name in ("node_x_dbu", "node_y_dbu"):
        value = topology.get(name)
        if torch.is_tensor(value):
            topology[name] = value.detach().cpu().reshape(-1).tolist()
    if candidate_state is None:
        records = ()
    elif hasattr(candidate_state, "candidate_records"):
        records = tuple(candidate_state.candidate_records)
    else:
        records = tuple(candidate_state or ())
    refreshed = []
    invalidated = []
    remapped_activation = None
    if hasattr(candidate_state, "activation_param"):
        activation = candidate_state.activation_param
        if activation is not None:
            remapped_activation = activation.detach().clone()
    for raw_record in records:
        record = dict(raw_record)
        coordinate = _candidate_coordinate(record, topology)
        if coordinate is None or not all(math.isfinite(value) for value in coordinate):
            invalidated.append(candidate_key(record))
            record["candidate_geometry_status"] = "invalidated_by_topology_refresh"
            refreshed.append(record)
            continue
        x_dbu, y_dbu = coordinate
        record["x_dbu"] = int(round(x_dbu))
        record["y_dbu"] = int(round(y_dbu))
        record["candidate_location_x_dbu"] = int(round(x_dbu))
        record["candidate_location_y_dbu"] = int(round(y_dbu))
        record["x_um"] = float(x_dbu) / float(topology.get("dbu", 1.0) or 1.0)
        record["y_um"] = float(y_dbu) / float(topology.get("dbu", 1.0) or 1.0)
        segment = _segment_fields(record)
        if segment is not None:
            _, parent, child, ratio = segment
            parent_coordinate = _node_coordinate(topology, parent, dbu=True)
            child_coordinate = _node_coordinate(topology, child, dbu=True)
            if parent_coordinate is not None and child_coordinate is not None:
                length = math.hypot(
                    child_coordinate[0] - parent_coordinate[0],
                    child_coordinate[1] - parent_coordinate[1],
                )
                record["segment_length_dbu"] = int(round(length))
                record["upstream_length_dbu"] = float(length * ratio)
                record["downstream_length_dbu"] = float(length * (1.0 - ratio))
                record["candidate_geometry_status"] = "refreshed"
        else:
            record["candidate_geometry_status"] = "refreshed"
        refreshed.append(record)

    generation = int(
        candidate_generation
        if candidate_generation is not None
        else topology.get("topology_generation", 0) or 0
    )
    resolved_geometry_generation = int(
        geometry_generation
        if geometry_generation is not None
        else topology.get("geometry_generation", generation) or generation
    )
    topology_digest = (
        "sha256:"
        + hashlib.sha256(
            json.dumps(
                {
                    "topology_generation": topology.get("topology_generation"),
                    "node_x_dbu": _tensor_digest_value(topology.get("node_x_dbu")),
                    "node_y_dbu": _tensor_digest_value(topology.get("node_y_dbu")),
                },
                sort_keys=True,
                separators=(",", ":"),
            ).encode("utf-8")
        ).hexdigest()
    )
    return CandidateRefreshResult(
        candidate_records=tuple(refreshed),
        candidate_generation=generation,
        geometry_generation=resolved_geometry_generation,
        remapped_activation=remapped_activation,
        invalidated_candidate_keys=tuple(invalidated),
        geometry_digest=_digest_records(refreshed),
        topology_digest=topology_digest,
    )


def _tensor_digest_value(value):
    if value is None:
        return None
    if torch.is_tensor(value):
        return value.detach().cpu().reshape(-1).tolist()
    try:
        return list(value)
    except TypeError:
        return value


@torch.no_grad()
def remap_candidate_state(old_state, new_state, *, invalidated_keys=()):
    """Transfer accepted virtual activation by candidate key after a rebuild."""

    if old_state is None or new_state is None:
        return {"status": "skipped", "reason": "missing_state", "matched_count": 0}
    old_records = tuple(getattr(old_state, "candidate_records", ()) or ())
    new_records = tuple(getattr(new_state, "candidate_records", ()) or ())
    old_rows = {candidate_key(record): index for index, record in enumerate(old_records)}
    old_activation = getattr(old_state, "activation_param", None)
    new_activation = getattr(new_state, "activation_param", None)
    if old_activation is None or new_activation is None:
        return {"status": "skipped", "reason": "non_discrete_candidate", "matched_count": 0}
    old_activation_value = old_activation.detach()
    old_candidate_ids = old_state.candidate_ids.detach().cpu().tolist()
    remapped = torch.zeros_like(new_activation)
    remapped_records = []
    remapped_candidate_ids = new_state.candidate_ids.detach().cpu().tolist()
    retained_ids = set()
    matched_rows = set()
    old_active_keys = set()
    if old_activation.ndim == 1:
        old_active_indices = torch.nonzero(old_activation.detach() > 0.0).flatten()
    else:
        old_active_indices = torch.nonzero(old_activation.detach().sum(dim=1) > 0.0).flatten()
    for old_index in old_active_indices.detach().cpu().tolist():
        old_active_keys.add(candidate_key(old_records[int(old_index)]))
    matched_keys = set()
    matched = 0
    source_indices = []
    destination_indices = []
    invalidated = set(invalidated_keys or ())
    for new_index, record in enumerate(new_records):
        key = candidate_key(record)
        old_index = old_rows.get(key)
        if old_index is None or key in invalidated:
            remapped_records.append(dict(record))
            continue
        source_indices.append(old_index)
        destination_indices.append(new_index)
        old_candidate_id = int(old_candidate_ids[old_index])
        remapped_candidate_ids[new_index] = old_candidate_id
        remapped_record = dict(record)
        remapped_record["candidate_id"] = old_candidate_id
        remapped_records.append(remapped_record)
        retained_ids.add(old_candidate_id)
        matched_rows.add(new_index)
        matched_keys.add(key)
        matched += 1
    if source_indices:
        source_index = torch.tensor(source_indices, device=old_activation_value.device)
        destination_index = torch.tensor(destination_indices, device=remapped.device)
        remapped.index_copy_(
            0,
            destination_index,
            old_activation_value.index_select(0, source_index).to(device=remapped.device),
        )
    next_candidate_id = max(retained_ids, default=-1) + 1
    for new_index, record in enumerate(remapped_records):
        if new_index >= len(remapped_candidate_ids):
            break
        if new_index in matched_rows:
            continue
        while next_candidate_id in retained_ids:
            next_candidate_id += 1
        record["candidate_id"] = next_candidate_id
        remapped_candidate_ids[new_index] = next_candidate_id
        retained_ids.add(next_candidate_id)
        next_candidate_id += 1
    new_state.activation_param = nn.Parameter(remapped)
    new_state.activation_param.requires_grad_(old_activation.requires_grad)
    if getattr(old_state, "is_typed_candidate", False):
        new_state.timing_active_only = old_state.timing_active_only
    new_state.candidate_ids = torch.tensor(
        remapped_candidate_ids,
        dtype=new_state.candidate_ids.dtype,
        device=new_state.candidate_ids.device,
    )
    new_state.candidate_records = tuple(remapped_records)
    remap_failed_keys = tuple(sorted(old_active_keys - matched_keys, key=str))
    return {
        "status": "ok" if not remap_failed_keys else "ok_with_invalidations",
        "matched_count": int(matched),
        "old_active_count": int(old_activation.detach().sum().cpu().item()),
        "new_active_count": int(remapped.detach().sum().cpu().item()),
        "invalidated_count": int(len(invalidated)),
        "candidate_state_remap_failed": list(remap_failed_keys),
    }


